"""
View and compare test results: generated vs golden concepts.
Usage: python view_results.py [results_file.json]
"""

import json
import sys
from pathlib import Path


def print_header(text: str, char: str = "="):
    """Print a formatted header."""
    print(f"\n{char * 80}")
    print(f"  {text}")
    print(f"{char * 80}\n")


def print_concept(concept: dict, label: str = ""):
    """Print a single concept in readable format."""
    if label:
        print(f"\n{label}")
        print("-" * 70)

    print(f"Headline:        {concept.get('headline', 'N/A')}")
    print(f"Content Pillar:  {concept.get('content_pillar', '(none)')}")
    print(f"Product:         {concept.get('product', '(none)')}")
    print(f"\nRationale:")
    print(f"  {concept.get('rationale', 'N/A')}")
    print(f"\nImage Generation Prompt:")
    prompt = concept.get('prompt', 'N/A')
    # Wrap long prompt
    words = prompt.split()
    line = ""
    for word in words:
        if len(line) + len(word) > 70:
            print(f"  {line}")
            line = word
        else:
            line = f"{line} {word}".strip()
    if line:
        print(f"  {line}")


def view_brand_results(brand_result: dict):
    """View detailed results for a single brand."""
    brand_name = brand_result.get("brand_name", "Unknown")
    print_header(f"Brand: {brand_name}", "=")

    # Overall scores
    print("OVERALL SCORES")
    print(f"  Overall Score:        {brand_result['overall_score']:.1%}")
    print(f"  Set Quality Average:  {brand_result['set_quality_avg']:.1%}")
    print(f"  Diversity Score:      {brand_result['diversity_score']:.1%}")
    print(f"  Approval Alignment:   {brand_result['approval_alignment']:.1%}")
    print(f"\n  Summary: {brand_result['summary']}\n")

    # Generated vs Golden concepts
    generated = brand_result.get("generated_concepts", [])
    golden = brand_result.get("golden_concepts", [])

    for idx in range(3):
        if idx < len(generated) and idx < len(golden):
            print_header(f"Concept {idx + 1}", "-")

            # Generated
            print_concept(generated[idx], "GENERATED BY CLAUDE:")

            # Golden
            print_concept(golden[idx], "GOLDEN STANDARD:")

            # Scores
            if idx < len(brand_result.get("concept_scores", [])):
                scores = brand_result["concept_scores"][idx]
                print("\nSCORES FOR THIS CONCEPT:")
                print(f"  Structural Quality:   {scores['structural']:.1%}")
                print(f"  Headline Quality:     {scores['headline']:.1%}")
                print(f"  Prompt Quality:       {scores['prompt']:.1%}")
                print(f"  Brand Faithfulness:   {scores['brand_faithfulness']:.1%}")
                print(f"  Rationale Quality:    {scores['rationale']:.1%}")
                print(f"  Overall:              {scores['overall']:.1%}")
                print(f"\n  Feedback: {scores['feedback']}")


def view_summary(results: dict):
    """View summary across all brands."""
    print_header("EVALUATION SUMMARY", "=")

    summary = results.get("summary", {})
    print("Overall Performance:")
    print(f"  Average Overall Score:      {summary.get('avg_overall_score', 0):.1%}")
    print(f"  Average Set Quality:        {summary.get('avg_quality', 0):.1%}")
    print(f"  Average Diversity:          {summary.get('avg_diversity', 0):.1%}")
    print(f"  Average Approval Alignment: {summary.get('avg_approval_alignment', 0):.1%}")

    print(f"\nTest Results:")
    print(f"  Successful Tests: {summary.get('successful_tests', 0)}")
    print(f"  Failed Tests:     {summary.get('failed_tests', 0)}")
    print(f"\nTimestamp: {results.get('timestamp', 'Unknown')}")


def main():
    """Main entry point."""
    if len(sys.argv) > 1:
        results_file = sys.argv[1]
    else:
        results_file = "test_results.json"

    path = Path(results_file)
    if not path.exists():
        print(f"Error: Results file not found: {results_file}")
        print("\nUsage: python view_results.py [results_file.json]")
        print("Default file: test_results.json")
        sys.exit(1)

    with open(path) as f:
        results = json.load(f)

    # Show summary
    view_summary(results)

    # Show individual brand results
    for brand_result in results.get("scores", []):
        if "error" not in brand_result:
            view_brand_results(brand_result)
        else:
            print_header(f"Brand: {brand_result.get('brand_name')} (ERROR)", "!")
            print(f"Error: {brand_result['error']}")

    # Comparison helpers
    print_header("HOW TO USE THESE RESULTS", "-")
    print("""
1. IDENTIFY WEAK AREAS
   - Low avg_overall_score? Check quality metrics
   - Low avg_diversity? Concepts may be too similar
   - Low avg_approval_alignment? Not learning from history

2. COMPARE GENERATED vs GOLDEN
   - Each concept pair shows Claude's output vs reference
   - Look at differences in headline, prompt detail, rationale
   - Read feedback for specific issues

3. ITERATE IMPROVEMENTS
   - Make changes to claude_orchestrator.py instruction
   - Re-run evaluation: python -m evaluation_framework
   - Compare new test_results.json to previous results

4. FOCUS ON CONTENT QUALITY
   - Prompt Quality: Should be 100-150 words, detailed
   - Brand Faithfulness: Uses pillars/products, respects avoid-lists
   - Headline Quality: Specific, engaging, relevant

5. ENSURE DIVERSITY
   - Diversity Score < 0.7? Concepts need more variation
   - Check if different pillars are used
   - Verify different subject matter/angles
    """)


if __name__ == "__main__":
    main()
